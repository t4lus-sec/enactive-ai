//! An audit reports through its project: the generated audit part of a
//! board's report, the results a report cites (frozen at the version cited),
//! and the cited re-runs verification makes from a clean checkout.

use crate::audit::{self, AuditStore, Repro, Review, Verdict, Who};

/// The audit part, under the agent's text in `board_report`: claims checked,
/// failures and their repros, what was ruled out, the levels, marked
/// `diagnostic` where they rest on unreviewed claims.
pub fn part(board: &str) -> Option<String> {
    let store = audit::store()?;
    let audits = crate::audit::ops::for_board(board);
    if audits.is_empty() {
        return None;
    }
    let mut out = String::from("\n\n---\n## Audit part (generated by the harness)\n");
    for audit in audits {
        let claims = store.claims(&audit.name).unwrap_or_default();
        let checked: Vec<_> = claims.iter().filter(|c| !matches!(c.verdict, Verdict::Unchecked)).collect();
        out.push_str(&format!(
            "\n### {} ({}, {})\n{} claims, {} checked.\n",
            audit.name,
            if audit.mode == audit::Mode::Diagnose { "diagnose" } else { "assure" },
            audit.status.label(),
            claims.len(),
            checked.len()
        ));
        for claim in &claims {
            let diagnostic = if claim.review == Review::Accepted { "" } else { " · diagnostic" };
            match (claim.verdict, claim.repro) {
                (Verdict::Fails, Repro::Fails) => out.push_str(&format!(
                    "- **{}/{} fails** (reproduced{diagnostic}): {} — repro `{}`\n",
                    audit.name,
                    claim.id,
                    claim.text,
                    claim.repro_test.as_deref().unwrap_or("?")
                )),
                (Verdict::Fails, Repro::ModelOnly) => out.push_str(&format!("- {}/{} fails in the model only: {}\n", audit.name, claim.id, claim.text)),
                (Verdict::Holds, _) => out.push_str(&format!(
                    "- {}/{} holds ({}{diagnostic}{}): {}\n",
                    audit.name,
                    claim.id,
                    claim.level.label(),
                    claim.kills.map(|(k, t)| format!(", {k}/{t} mutants")).unwrap_or_default(),
                    claim.text
                )),
                _ => {}
            }
        }
        let mut levels: std::collections::BTreeMap<&str, usize> = std::collections::BTreeMap::new();
        for claim in &claims {
            *levels.entry(claim.level.label()).or_default() += 1;
        }
        out.push_str(&format!("Levels: {}\n", levels.iter().map(|(l, n)| format!("{l} {n}")).collect::<Vec<_>>().join(" · ")));
    }
    Some(out)
}

/// The results a report cites (`share-slice/c9`), recorded as cited by this
/// round: their checks are frozen at the version cited (rule 4 applies), and
/// verification re-runs exactly these.
pub fn cite(board: &str, report: &str, round: i64) -> Vec<(String, String)> {
    let Some(store) = audit::store() else { return Vec::new() };
    let audits: Vec<String> = crate::audit::ops::for_board(board).into_iter().map(|a| a.name).collect();
    let mut cited = Vec::new();
    for word in report.split(|c: char| c.is_whitespace() || matches!(c, '(' | ')' | ',' | ';' | '`' | '*')) {
        let Some((audit, claim)) = word.trim_end_matches(['.', ':']).split_once('/') else { continue };
        if !audits.iter().any(|a| a == audit) || !claim.starts_with(['c', 'a']) {
            continue;
        }
        if store.claim(audit, claim).ok().flatten().is_none() || cited.iter().any(|(a, c)| a == audit && c == claim) {
            continue;
        }
        let tag = format!("{board} round {round}");
        let _ = store.change_claim(audit, claim, |c| {
            if !c.cited.contains(&tag) {
                c.cited.push(tag.clone());
            }
            Ok(())
        });
        cited.push((audit.to_string(), claim.to_string()));
    }
    cited
}

/// Verification: every cited result re-run from a clean checkout of the
/// audited commit (a fresh copy of a folder), with nothing of the agent's in it.
/// A cited result that doesn't come out the same fails. Whether all came
/// out the same, and what each did.
pub fn rerun_cited(store: &AuditStore, name: &str, ids: &[&str]) -> std::result::Result<(bool, String), String> {
    let audit = store.audit(name).map_err(|e| e.to_string())?.ok_or(format!("no audit {name}"))?;
    let clean = format!("{}-verify", audit.work.trim_end_matches('/'));
    let setup = if audit.kind == "git" {
        format!(
            "rm -rf {c}; git -C {w} worktree add -q --detach {c} {commit} >/dev/null 2>&1 || exit 5; cp -a {w}/checks {c}/ 2>/dev/null; echo ok",
            c = crate::util::shell_quote(&clean),
            w = crate::util::shell_quote(&audit.work),
            commit = if audit.commit.is_empty() { "HEAD".to_string() } else { audit.commit.clone() }
        )
    } else {
        format!("rm -rf {c}; cp -a {w} {c} && echo ok", c = crate::util::shell_quote(&clean), w = crate::util::shell_quote(&audit.work))
    };
    let ran = crate::vm::netboxes::machine(&setup, 300)?;
    if !ran.stdout.contains("ok") {
        return Err(format!("a clean checkout could not be made: {}", ran.stderr.trim()));
    }
    let mut clean_audit = audit.clone();
    clean_audit.work = clean.clone();
    let mut same = true;
    let mut lines = Vec::new();
    for id in ids {
        let Some(claim) = store.claim(name, id).map_err(|e| e.to_string())? else { continue };
        // The check at the version cited: the current one, frozen since.
        if let Some(check) = store.current_check(name, id).map_err(|e| e.to_string())? {
            let ran = crate::audit::run::in_shell(&clean_audit, id, "verification: re-run as cited", &check.run, check.timeout)?;
            let (verdict, _) = crate::audit::run::verdict_of(ran.exit, ran.interrupted);
            let agrees = verdict == claim.verdict || (claim.verdict == Verdict::Vacuous && verdict == Verdict::Holds);
            same &= agrees;
            lines.push(format!("{name}/{id} check: {} (recorded {}){}", verdict.label(), claim.verdict.label(), if agrees { "" } else { " — DIFFERS" }));
        }
        if claim.repro == Repro::Fails
            && let Some(spec) = &claim.repro_test
        {
            let command = spec.split_once(" :: ").map(|(_, c)| c).unwrap_or(spec);
            let ran = crate::audit::run::in_shell(&clean_audit, id, "verification: the repro must still fail on the audited code", command, audit.settings.check_secs)?;
            let fails = ran.exit.is_some_and(|e| e != 0);
            same &= fails;
            lines.push(format!("{name}/{id} repro: {}", if fails { "fails on the audited code, as recorded" } else { "PASSES — differs" }));
        }
    }
    let _ = store.log(name, Who::Harness, &format!("verification re-ran {} cited result(s): {}", ids.len(), if same { "the same" } else { "a difference" }), &lines.join("; "));
    let _ = crate::vm::netboxes::machine(&format!("git -C {} worktree remove --force {} >/dev/null 2>&1 || rm -rf {}", crate::util::shell_quote(&audit.work), crate::util::shell_quote(&clean), crate::util::shell_quote(&clean)), 120);
    Ok((same, lines.join("\n")))
}

/// The claims of `audit` a report of `board` cited: exactly what
/// verification re-runs, no more and no fewer.
pub fn cited_ids(store: &AuditStore, audit: &str, board: &str) -> Vec<String> {
    store.claims(audit).unwrap_or_default().into_iter().filter(|c| c.cited.iter().any(|t| t.starts_with(&format!("{board} round")))).map(|c| c.id).collect()
}

/// When a board enters verification: its cited results re-run, and the gate
/// (`--holding`) if the operator set one, written to
/// `/share/<board>/audit-verification.md` for the verifier to read.
pub fn verify_in_background(board: String, share_folder: String) {
    if cfg!(test) {
        return;
    }
    let _ = std::thread::Builder::new().name("audit-verify".into()).spawn(move || {
        let Some(store) = audit::store() else { return };
        let mut text = format!("# Audit verification for {board}\n\nRe-run by the harness from a clean checkout.\n\n");
        let mut ok = true;
        for audit in crate::audit::ops::for_board(&board) {
            let ids = cited_ids(&store, &audit.name, &board);
            if !ids.is_empty() {
                let refs: Vec<&str> = ids.iter().map(String::as_str).collect();
                match rerun_cited(&store, &audit.name, &refs) {
                    Ok((same, lines)) => {
                        ok &= same;
                        text.push_str(&format!("## {} (cited)\n{lines}\n\n", audit.name));
                    }
                    Err(error) => {
                        ok = false;
                        text.push_str(&format!("## {} (cited)\ncould not re-run: {error}\n\n", audit.name));
                    }
                }
            }
        }
        for gate in crate::audit::run::gates(&board) {
            if let Some(run) = crate::audit::run::command(&format!("audit-run {gate} --holding")) {
                ok &= run.exit_code == Some(0);
                text.push_str(&format!("## gate: audit-run {gate} --holding\nexit {:?}: {}\n\n", run.exit_code, run.stdout));
            }
        }
        text.push_str(&format!("\nRESULT: {}\n", if ok { "the same" } else { "DIFFERS — verification fails" }));
        let path = format!("{}/{share_folder}/audit-verification.md", crate::share::share_dir());
        let _ = crate::vm::netboxes::machine(
            &format!("printf %s '{}' | base64 -d > {}", base64::Engine::encode(&base64::engine::general_purpose::STANDARD, text.as_bytes()), crate::util::shell_quote(&path)),
            30,
        );
    });
}

/// At complete: the reproduced failures, offered as regression tests with
/// the fix, and what to do with each audit.
pub fn at_complete(board: &str) -> Option<String> {
    let store = audit::store()?;
    let audits = crate::audit::ops::for_board(board);
    if audits.is_empty() {
        return None;
    }
    let mut lines = Vec::new();
    for audit in audits.iter().filter(|a| a.board.as_deref() == Some(board)) {
        let repros: Vec<String> = store
            .claims(&audit.name)
            .unwrap_or_default()
            .into_iter()
            .filter(|c| c.repro == Repro::Fails)
            .filter_map(|c| c.repro_test.map(|t| format!("{}: {}", c.id, t.split(" :: ").next().unwrap_or(&t))))
            .collect();
        lines.push(format!(
            "audit {}: {} — /audit letgo {} (the default for diagnose) or /audit keep {}{}",
            audit.name,
            audit.status.label(),
            audit.name,
            audit.name,
            if repros.is_empty() { String::new() } else { format!(". Regression tests: {}", repros.join("; ")) }
        ));
    }
    Some(lines.join("\n"))
}
